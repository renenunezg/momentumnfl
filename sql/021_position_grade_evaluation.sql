begin;

-- Holdout and cross-validated accuracy of the player grades, precomputed so
-- the site reads it as published (the nfl.performance_metrics convention).
-- One row per model, position, evaluation, sample and baseline: the grade's
-- Spearman rank correlation with the outcome against a baseline's on the
-- identical players, the difference, and its 95% bootstrap interval.
--
-- evaluation: next_season (final-week grade in t against per-game EPA credit
--   in t+1, survivors at the same position) or rest_of_season (the rating at
--   each checkpoint week against the rest of that season, averaged over
--   seasons per week and over weeks 3 to 16; checkpoint_week null is that
--   average).
-- sample_set: development_cv (leave-one-season-out or cross-fitted on the
--   development seasons) or validation (the frozen model on the validation
--   season).
-- holdout_status: development for development rows; for validation rows,
--   clean (never seen before the model froze), viewed (printed before the
--   last model choices) or screened (also used to screen the model's
--   candidate measures).
-- difference_ci: a player-level bootstrap (4,000 resamples per season pair
--   for the trait grades, 1,000 for the ratings' validation season and 250
--   for their development seasons). Null where the grade's development
--   number is cross-fitted and the bootstrap is not (QB and RB trait grades).
-- thin_sample: fewer than 100 player-seasons behind the row.
create table nfl.position_grade_evaluation (
  model_version text not null,
  position_group text not null,
  evaluation text not null check (evaluation in ('next_season', 'rest_of_season')),
  sample_set text not null check (sample_set in ('development_cv', 'validation')),
  seasons text not null,
  validation_season integer not null,
  checkpoint_week integer check (checkpoint_week between 1 and 18),
  target text not null,
  players integer,
  player_seasons integer not null,
  grade_spearman double precision not null,
  baseline text not null,
  baseline_spearman double precision not null,
  difference double precision not null,
  difference_ci_low double precision,
  difference_ci_high double precision,
  thin_sample boolean not null,
  holdout_status text not null
    check (holdout_status in ('development', 'clean', 'viewed', 'screened')),
  computed_at timestamptz not null,
  unique nulls not distinct
    (model_version, position_group, evaluation, sample_set, checkpoint_week, baseline),
  check (difference_ci_low is null or difference_ci_low <= difference_ci_high)
);

alter table nfl.position_grade_evaluation enable row level security;
create policy "anon read" on nfl.position_grade_evaluation
  for select to anon, authenticated using (true);
grant select on nfl.position_grade_evaluation to anon, authenticated;
grant select, insert, delete on nfl.position_grade_evaluation to service_role;

create trigger site_revalidate
  after insert or delete or update or truncate on nfl.position_grade_evaluation
  for each statement execute function public.site_revalidate();

-- Replaces every row of the model versions in the payload with the payload's
-- rows in one statement each, so a republish cannot leave a stale baseline
-- behind and the revalidation trigger fires once per statement. The payload
-- is a JSON array of objects keyed like the table's columns, without
-- computed_at; returns the number of rows written.
create function nfl.publish_position_grade_evaluation(payload jsonb)
returns integer
language plpgsql set search_path = pg_catalog, nfl as $$
declare
  written integer;
begin
  if jsonb_typeof(payload) <> 'array' or jsonb_array_length(payload) = 0 then
    raise exception 'position grade evaluation payload must be a non-empty array';
  end if;
  delete from nfl.position_grade_evaluation
  where model_version in (
    select distinct value->>'model_version' from jsonb_array_elements(payload)
  );
  insert into nfl.position_grade_evaluation (
    model_version, position_group, evaluation, sample_set, seasons,
    validation_season, checkpoint_week, target, players, player_seasons,
    grade_spearman, baseline, baseline_spearman, difference,
    difference_ci_low, difference_ci_high, thin_sample, holdout_status,
    computed_at
  )
  select
    r.model_version, r.position_group, r.evaluation, r.sample_set, r.seasons,
    r.validation_season, r.checkpoint_week, r.target, r.players, r.player_seasons,
    r.grade_spearman, r.baseline, r.baseline_spearman, r.difference,
    r.difference_ci_low, r.difference_ci_high, r.thin_sample, r.holdout_status,
    now()
  from jsonb_to_recordset(payload) as r(
    model_version text, position_group text, evaluation text, sample_set text,
    seasons text, validation_season integer, checkpoint_week integer, target text,
    players integer, player_seasons integer, grade_spearman double precision,
    baseline text, baseline_spearman double precision, difference double precision,
    difference_ci_low double precision, difference_ci_high double precision,
    thin_sample boolean, holdout_status text
  );
  get diagnostics written = row_count;
  return written;
end;
$$;
revoke all on function nfl.publish_position_grade_evaluation(jsonb) from public, anon, authenticated;
grant execute on function nfl.publish_position_grade_evaluation(jsonb) to service_role;

